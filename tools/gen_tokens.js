function findElement(data, matcher) {
    return data.elements.find(el => {
        if (matcher.framerName && el.framerName.includes(matcher.framerName)) return true;
        if (matcher.text && el.textContent.includes(matcher.text)) return true;
        if (matcher.src && el.src.includes(matcher.src)) return true;
        return false;
    });
}

